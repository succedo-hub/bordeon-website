import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import {
  ArrowUpRight, ArrowRight, ArrowLeft, ArrowDown, X, Plus, CircleDot,
  BriefcaseBusiness, FileText, FilePenLine, Network, TableProperties, Wallet,
} from 'lucide-static';

const root = new URL('../', import.meta.url);
const icons = {
  'arrow-up-right': ArrowUpRight, 'arrow-right': ArrowRight,
  'arrow-left': ArrowLeft, 'arrow-down': ArrowDown, x: X, plus: Plus,
  'circle-dot': CircleDot, 'briefcase-business': BriefcaseBusiness,
  'file-text': FileText, 'file-pen-line': FilePenLine, network: Network,
  'table-properties': TableProperties, wallet: Wallet,
};
const symbols = Object.entries(icons).map(([name, svg]) => {
  const paths = svg.trim().match(/^<svg\b[^>]*>([\s\S]*)<\/svg>$/)?.[1];
  if (!paths) throw new Error(`Invalid Lucide SVG: ${name}`);
  return `<symbol id="${name}" viewBox="0 0 24 24">${paths.trim()}</symbol>`;
});
await mkdir(new URL('dist/assets/', root), { recursive: true });
await mkdir(new URL('dist/vendor/', root), { recursive: true });
await writeFile(new URL('dist/assets/icons.svg', root),
  `<!-- Lucide icons, ISC license: /vendor/lucide-LICENSE.txt -->\n<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('\n')}</svg>\n`);
await copyFile(new URL('node_modules/lucide-static/LICENSE', root), new URL('dist/vendor/lucide-LICENSE.txt', root));

// Runtime controls use the same sprite, size and stroke as static HTML icons.
await writeFile(new URL('dist/icons.js', root), `// Generated by scripts/build-icons.mjs. Lucide icons, ISC license.\n(() => {\n  const names = new Set(${JSON.stringify(Object.keys(icons))});\n  window.BordeonIcons = Object.freeze({\n    icon(name) {\n      if (!names.has(name)) throw new Error('Unknown icon: ' + name);\n      return '<svg class="icon" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><use href="/assets/icons.svg#' + name + '"></use></svg>';\n    }\n  });\n})();\n`);
console.log(`Built ${symbols.length} Lucide SVG icons.`);
